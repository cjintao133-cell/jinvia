static int run(const uint8_t *buf, size_t len, uint32_t fn, const int64_t *args, uint32_t na, int64_t *out){
    JModule m;
    if(j_parse(buf,len,&m)!=J_OK) return -100;
    JVM *vm=j_vm_new(&m);
    if(!vm){ j_free(&m); return -101; }
    j_vm_set_host(vm, host_double, NULL);
    int rc=j_vm_call(vm,fn,args,na,out);
    j_vm_free(vm); j_free(&m);
    return rc;
}
